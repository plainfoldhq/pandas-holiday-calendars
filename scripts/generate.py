"""Generate free/src/pandas_holiday_calendars/_data.py from the `holidays` library.

    /path/to/python scripts/generate.py

Not shipped in the package. Only weekday closures are kept (a holiday on a Saturday or Sunday
that gives no weekday off is dropped). Years just outside the range are fetched so that observed
dates that cross a year boundary (e.g. 2021-12-31 for New Year's Day 2022) are not lost.
"""
import os
from datetime import date

import holidays

SOURCES = {
    "NYSECalendar": ((2000, 2050), lambda y: holidays.financial_holidays("XNYS", years=y)),
    "FederalReserveCalendar": ((2000, 2050), lambda y: holidays.financial_holidays("XFED", years=y)),
    "USFederalCalendar": ((2000, 2050), lambda y: holidays.country_holidays("US", years=y)),
    "EnglandWalesCalendar": ((2026, 2028), lambda y: holidays.country_holidays("GB", subdiv="ENG", years=y)),
    "EuroT2Calendar": ((2026, 2028), lambda y: holidays.financial_holidays("XECB", years=y)),
}
HERE = os.path.dirname(os.path.abspath(__file__))
# works from products/pandas-calendars/scripts (package in ../free) and from <repo>/scripts (package in ../src)
ROOT = os.path.join(HERE, "..", "free") if os.path.isdir(os.path.join(HERE, "..", "free")) else os.path.join(HERE, "..")
OUT = os.path.join(ROOT, "src", "pandas_holiday_calendars", "_data.py")


def build(name):
    (first, last), make = SOURCES[name]
    lib = make(range(first - 1, last + 2))
    rows = []
    for d, label in sorted(lib.items()):
        if d.weekday() < 5 and date(first, 1, 1) <= d <= date(last, 12, 31) and "Inauguration" not in label:
            rows.append((d.isoformat(), label))
    return (first, last), rows


def main():
    lines = ['"""Embedded holiday dates. Generated by scripts/generate.py from `holidays` %s: do not edit."""' % holidays.__version__,
             "", "COVERAGE = {"]
    built = {n: build(n) for n in SOURCES}
    for n, (cov, _) in built.items():
        lines.append("    %r: %r," % (n, cov))
    lines += ["}", "", "DATES = {"]
    for n, (_, rows) in built.items():
        lines.append("    %r: (" % n)
        lines += ["        (%r, %r)," % r for r in rows]
        lines.append("    ),")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    for n, (_, rows) in built.items():
        print(n, len(rows))


if __name__ == "__main__":
    main()
